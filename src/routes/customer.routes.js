import {Router} from 'express';
import * as c from '../controllers/customer.controller.js';
import {rateProduct} from '../controllers/variants.controller.js';
import {authenticate,authorize} from '../middleware/auth.js';
import {validate} from '../middleware/validate.js';
import {addressSchema,cartSchema,checkoutSchema,searchHistorySchema,supportTicketSchema} from '../validators/schemas.js';

export const customerRouter=Router();
const authCustomer=[authenticate,authorize('CUSTOMER')];
customerRouter.put('/products/:id/rating',authCustomer,rateProduct);
customerRouter.get('/users/me',authCustomer,c.profile.get);
customerRouter.patch('/users/me',authCustomer,c.profile.update);
customerRouter.get('/addresses',authCustomer,c.addresses.list);
customerRouter.post('/addresses',authCustomer,validate(addressSchema),c.addresses.create);
customerRouter.patch('/addresses/:id',authCustomer,c.addresses.update);
customerRouter.delete('/addresses/:id',authCustomer,c.addresses.remove);
customerRouter.patch('/addresses/:id/default',authCustomer,c.addresses.makeDefault);
customerRouter.get('/favorites',authCustomer,c.favorites.list);
customerRouter.post('/favorites/:productId',authCustomer,c.favorites.add);
customerRouter.delete('/favorites/:productId',authCustomer,c.favorites.remove);
customerRouter.get('/cart',authCustomer,c.cart.get);
customerRouter.put('/cart/items',authCustomer,validate(cartSchema),c.cart.set);
customerRouter.delete('/cart',authCustomer,c.cart.clear);
customerRouter.get('/search-history',authCustomer,c.searchHistory.list);
customerRouter.post('/search-history',authCustomer,validate(searchHistorySchema),c.searchHistory.add);
customerRouter.delete('/search-history/:query',authCustomer,c.searchHistory.remove);
customerRouter.delete('/search-history',authCustomer,c.searchHistory.clear);
customerRouter.get('/coupons',authCustomer,c.coupons);
customerRouter.post('/coupons/validate',authCustomer,c.couponValidate);
customerRouter.post('/checkout',authCustomer,validate(checkoutSchema),c.checkout);
customerRouter.get('/orders',authCustomer,c.orders.list);
customerRouter.get('/orders/:id',authCustomer,c.orders.get);
customerRouter.get('/support',authCustomer,c.support.list);
customerRouter.post('/support',authCustomer,validate(supportTicketSchema),c.support.create);
